#!/bin/sh
#
#  make-demo-epub-source.sh
#  Paperbound
#
#  Embeds PaperboundTests/Fixtures/Sample.epub in the app as a DEBUG-only
#  Swift source, Paperbound/Library/DemoEPUBData.swift, for the
#  `-paperbound-demo-epub` launch argument.
#
#  A Swift file rather than a bundled resource because the synchronized
#  Paperbound folder copies resources into every configuration; wrapped in
#  `#if DEBUG`, the bytes never reach a release build.
#
#  Run after Tools/make-epub-fixtures.sh whenever the sample book changes.
#
#  Usage: Tools/make-demo-epub-source.sh   (from anywhere)
#

set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
EPUB="$ROOT/PaperboundTests/Fixtures/Sample.epub"
OUT="$ROOT/Paperbound/Library/DemoEPUBData.swift"

{
    echo "//"
    echo "//  DemoEPUBData.swift"
    echo "//  Paperbound"
    echo "//"
    echo "//  GENERATED by Tools/make-demo-epub-source.sh from"
    echo "//  PaperboundTests/Fixtures/Sample.epub. Do not edit by hand."
    echo "//"
    echo "//  DEBUG only: the sample EPUB for \`-paperbound-demo-epub\`."
    echo "//"
    echo ""
    echo "#if DEBUG"
    echo "import Foundation"
    echo ""
    echo "extension DemoEPUB {"
    echo "    static let sampleBase64: String = \"\"\""
    base64 -i "$EPUB" | fold -w 100
    echo "\"\"\""
    echo "}"
    echo "#endif"
} > "$OUT"

echo "Wrote $OUT"
